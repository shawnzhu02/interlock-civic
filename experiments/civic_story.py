"""
The judge-facing civic story, generated by the REAL Interlock engine.

Runs six scenarios for the fictional Riverside County Benefits Office against a
real ``CivicOffice`` (the simulated case system, ledger and scheduler from
``backend/civic``, and the simulated payment rail ``Payments(tier=1)``). No
network, no Stripe key. Every decision, refusal, recovery and receipt comes from
``interlock/`` and ``backend/civic`` -- nothing here is hand-written sample data.

    python -X utf8 experiments/civic_story.py

writes ``demo/civic_data.js`` as ``window.CIVIC = {...}`` for ``demo/civic.html``.

Determinism: a fixed clock and a fresh temp directory per scenario, so the file
is byte-stable across runs (the journal timestamps come from the injected clock).
"""
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from backend.civic.office import CivicOffice
from interlock.escalation import describe, explain, latest
from interlock.receipts import verify

# A fixed clock. Each scenario advances it in whole seconds so the journal is
# deterministic; nothing here reads the wall clock.
START = 1_700_000_000


class Clock:
    def __init__(self, start=START):
        self.t = float(start)

    def __call__(self):
        return self.t

    def tick(self, seconds=1):
        self.t += seconds
        return self.t


def money(amount):
    return f"${amount:,.2f}"


def facts_table(facts):
    """The premises a rule read, as ordered label/value pairs for display."""
    labels = [
        ("entitlement", "Entitlement for the period"),
        ("prior_reissues", "Reissues already made this period"),
        ("eligible", "Case eligible"),
        ("active", "Case active"),
    ]
    out = []
    for key, label in labels:
        if key in facts:
            value = facts[key]
            if key == "entitlement" and value is not None:
                value = money(value)
            out.append({"label": label, "value": value})
    return out


def queue_item(office, request_id):
    """The caseworker queue entry for this request, with describe() wording, or None."""
    item = office.payments.queue.get(request_id) or office.scheduling.queue.get(request_id) \
        or office.records.queue.get(request_id)
    if item is None:
        # The chain may hold an escalation even if the cache was rebuilt; read the journal.
        for inbox in (office.payments, office.scheduling, office.records):
            es = inbox._chain(request_id)
            e = latest(es)[0]
            if e is not None:
                item = {"request": None, "why": e["why"], "detail": e["detail"],
                        "facts": e["facts"], "changes": e["changes"], "repairs": e["repairs"],
                        "reason": e["reason"], "group": e["group"], "routed_to": e["routed_to"]}
                break
    if item is None:
        return None
    esc = {"why": item["why"], "changes": item.get("changes") or [],
           "repairs": item.get("repairs") or []}
    return {
        "reason": item.get("reason"),
        "why": item["why"],
        "detail": item.get("detail"),
        "routed_to": item.get("routed_to"),
        "changes": item.get("changes") or [],
        "suggested_fix": describe(esc),
        "facts": facts_table(item.get("facts") or {}),
    }


def resident_status(receipt, action_label):
    """
    Plain-language, grade-6 status derived from the receipt's four facts and final
    state. Never says "done" before the evidence says confirmed or later
    (.kiro/steering/receipts.md).
    """
    final = receipt["final"]
    executed = receipt["executed"]
    if executed is True:
        headline = f"Your {action_label} is done."
        body = ("We checked the office records. The action went through and is "
                "saved on your case. You do not need to do anything.")
        state = "recorded"
    elif executed == "unknown":
        headline = f"We are still checking your {action_label}."
        body = ("We started your action but have not been able to confirm it yet. "
                "We will check again and update your case. You do not need to do "
                "anything right now.")
        state = "checking"
    else:
        headline = f"Your {action_label} is on hold."
        body = ("A caseworker needs to look at your case before this can go ahead. "
                "We did this to keep your money and your case safe. A person will "
                "review it soon.")
        state = "on hold with a caseworker"
    return {"headline": headline, "body": body, "state": state}


def build_receipt(office, inbox, request_id):
    """The signed-shape receipt bundle (entries + verify result), from the real journal."""
    from interlock.journal import effect_id_for
    eid = effect_id_for({"request_id": request_id})
    bundle = inbox.gate.receipt_bundle({"request_id": request_id})
    result = verify(bundle)
    return eid, bundle, result


def journal_timeline(entries):
    """The journal entries as a compact, display-ready timeline."""
    out = []
    for e in entries:
        row = {"kind": e["kind"], "hash": (e.get("hash") or "")[:12]}
        if e["kind"] == "REFUSED":
            row["note"] = e.get("reason")
            row["code"] = e.get("code")
        elif e["kind"] == "ESCALATED":
            row["note"] = e.get("why")
        elif e["kind"] == "COMMITTED":
            row["note"] = "effect applied and confirmed"
        elif e["kind"] == "DISPATCHED":
            row["note"] = "about to apply (written to disk first)"
        elif e["kind"] == "AMBIGUOUS":
            row["note"] = "crash left the outcome unknown"
        out.append(row)
    return out


def scenario(title, request_summary, assistant_proposal, run):
    """Run one scenario body ``run(office, clock) -> dict`` in a fresh temp dir."""
    clock = Clock()
    with tempfile.TemporaryDirectory(prefix="civic-story-") as directory:
        office = CivicOffice(directory, clock=clock)
        body = run(office, clock)
    body.update(title=title, request=request_summary, proposed=assistant_proposal)
    return body


# --- scenario fixtures ------------------------------------------------------

def seed_case(office, case_id="case-7001", resident="res-maria", period="2026-09",
              entitlement=412, eligible=True, active=True, caseworker="ana",
              address="12 Oak St, Riverside"):
    office.case_store.add_resident(resident, "Maria (simulated resident)")
    office.case_store.add_case(case_id, resident, eligible=eligible, active=active,
                               address=address, caseworker=caseworker)
    office.case_store.set_entitlement(case_id, period, entitlement)
    return case_id, period


def common(office, inbox, request_id, action_label, status):
    """The shared per-scenario output: outcome, queue, resident view, receipt, journal."""
    eid, bundle, result = build_receipt(office, inbox, request_id)
    receipt = bundle["summary"]
    return {
        "effect_id": eid,
        "gate_outcome": status,
        "receipt": {
            "proposed": receipt["proposed"],
            "authorized": receipt["authorized"],
            "executed": receipt["executed"],
            "recorded": receipt["recorded"],
            "final": receipt["final"],
            "verified": result["valid"],
            "happened": result["happened"],
            "happened_once": result["happened_once"],
            "authorized_when_fired": result["authorized_when_fired"],
            "assumptions_held": result["assumptions_held"],
            "refused": result["refused"],
        },
        "journal": journal_timeline(bundle["entries"]),
        "caseworker": queue_item(office, request_id),
        "resident": resident_status(receipt, action_label),
    }


# --- (a) routine $412 reissue commits ---------------------------------------

def scenario_a(office, clock):
    case_id, period = seed_case(office)
    request = {"id": "a-reissue", "action": "reissue_payment", "case_id": case_id,
               "period": period, "amount": 412}
    status = office.submit(request)
    changed = [{"field": "ledger", "was": "no reissue for 2026-09",
                "now": "reissue of $412.00 recorded"}]
    out = common(office, office.payments, request["id"], "payment reissue", status)
    out["changed"] = changed
    return out


# --- (b) $4,120 on a $412 entitlement, refused before send ------------------

def scenario_b(office, clock):
    case_id, period = seed_case(office)
    request = {"id": "b-reissue", "action": "reissue_payment", "case_id": case_id,
               "period": period, "amount": 4120}
    status = office.submit(request)
    out = common(office, office.payments, request["id"], "payment reissue", status)
    out["changed"] = []
    out["limit_named"] = (f"The request was {money(4120)}, but the case's entitlement "
                          f"for {period} is {money(412)}. The rule 'within entitlement' "
                          f"stopped it before any money moved.")
    return out


# --- (c) second reissue for a period already reissued by hand ---------------

def scenario_c(office, clock):
    case_id, period = seed_case(office)
    # A caseworker already reissued this period by hand, straight into the ledger.
    office.ledger.record(case_id, "reissue", 412, period=period, source="caseworker:ben")
    request = {"id": "c-reissue", "action": "reissue_payment", "case_id": case_id,
               "period": period, "amount": 412}
    status = office.submit(request)
    out = common(office, office.payments, request["id"], "payment reissue", status)
    out["changed"] = []
    out["limit_named"] = (f"A caseworker already reissued {period} by hand. The rule "
                          f"'at most one reissue per period' counts every source from the "
                          f"ledger, so the assistant's second reissue was stopped.")
    return out


# --- (d) case closed while the assistant was deciding -----------------------

def scenario_d(office, clock):
    case_id, period = seed_case(office)
    # Bind the proposal on the facts as they were (eligible/active), the way the
    # inbox records a proposal before a person sees it: we drive the gate directly
    # so we can change the world between PROPOSED and dispatch.
    request = {"id": "d-reissue", "action": "reissue_payment", "case_id": case_id,
               "period": period, "amount": 412}
    inbox = office.payments
    facts = inbox.capture(request)                      # eligible + active now
    proposal = inbox._proposal(request, {"by": "policy", "rules": []}, facts)
    # A caseworker closes the case while the assistant is mid-decision.
    office.case_store.set_status(case_id, active=False)
    clock.tick()
    status = inbox.gate.submit(proposal)                # re-validates premises at send time
    out = common(office, inbox, request["id"], "payment reissue", status)
    out["changed"] = [{"field": "active", "was": True, "now": False}]
    out["limit_named"] = ("The case was closed by a caseworker after the assistant "
                          "decided but before the payment was sent. The gate re-read the "
                          "case at send time, saw it was no longer active, and refused.")
    return out


# --- (e) crash after send, then restart: recovered, exactly one payment ------

def scenario_e(office, clock):
    case_id, period = seed_case(office)
    request = {"id": "e-reissue", "action": "reissue_payment", "case_id": case_id,
               "period": period, "amount": 412}
    inbox = office.payments
    facts = inbox.capture(request)
    proposal = inbox._proposal(request, {"by": "policy", "rules": []}, facts)
    # The payment is sent, then the process dies before the ack returns.
    from interlock.gate import SimulatedCrash
    crashed = False
    try:
        inbox.gate.submit(proposal, crash_after_effect=True)
    except SimulatedCrash:
        crashed = True
    clock.tick()
    # Restart: recovery settles the one in-flight effect. Tier 1 retry is exactly-once.
    recovered = inbox.gate.recover(now=clock())
    status = "COMMITTED (recovered)" if any(
        s.startswith("COMMITTED") or s == "REAPPLIED_AFTER_QUERY" for s in recovered.values()
    ) else "; ".join(recovered.values())
    out = common(office, inbox, request["id"], "payment reissue", status)
    # Exactly one refund exists in the simulated rail for this effect id.
    refunds = [r for r in office.payment_rail.backend.refunds]
    out["changed"] = [
        {"field": "process", "was": "sent the payment", "now": f"crashed before the ack (crash seen: {crashed})"},
        {"field": "recovery", "was": "one effect in flight", "now": f"settled to {status}"},
        {"field": "payments made", "was": "at risk of double-pay", "now": f"exactly {len(refunds)}"},
    ]
    out["limit_named"] = ("The process crashed right after sending the payment. On restart, "
                          "recovery found the one in-flight effect and settled it. Because the "
                          "payment rail dedupes on the effect id (tier 1), exactly one payment "
                          f"exists: {len(refunds)}.")
    return out


# --- (f) appointment booking and address change both commit -----------------

def scenario_f(office, clock):
    case_id, period = seed_case(office)
    book = {"id": "f-book", "action": "book_appointment", "case_id": case_id,
            "office": "Riverside Main (simulated)", "slot": "2026-10-02 10:00"}
    addr = {"id": "f-address", "action": "change_address", "case_id": case_id,
            "new_address": "99 Pine Ave, Riverside"}
    book_status = office.submit(book)
    clock.tick()
    addr_status = office.submit(addr)

    book_out = common(office, office.scheduling, book["id"], "appointment booking", book_status)
    addr_out = common(office, office.records, addr["id"], "address change", addr_status)
    book_out["changed"] = [{"field": "scheduler", "was": "no booking",
                            "now": "appointment booked (simulated)"}]
    addr_out["changed"] = [{"field": "mailing address", "was": "12 Oak St, Riverside",
                            "now": "99 Pine Ave, Riverside"}]
    # Two actions in one scenario: present them as sub-actions.
    return {
        "effect_id": book_out["effect_id"],
        "gate_outcome": f"booking: {book_status}; address: {addr_status}",
        "sub_actions": [
            {"name": "Book appointment", **_sub(book_out)},
            {"name": "Change address", **_sub(addr_out)},
        ],
        # Top-level panels show the booking by default; the UI also lists sub_actions.
        "receipt": book_out["receipt"],
        "journal": book_out["journal"],
        "caseworker": book_out["caseworker"],
        "resident": book_out["resident"],
        "changed": book_out["changed"],
    }


def _sub(out):
    return {k: out[k] for k in ("effect_id", "gate_outcome", "receipt", "journal",
                                "caseworker", "resident", "changed")}


SCENARIOS = [
    ("a", lambda: scenario(
        "Routine reissue ($412)",
        "A resident messages: 'My September payment never came.'",
        "The assistant proposes reissuing the $412 September payment and closing the case.",
        scenario_a)),
    ("b", lambda: scenario(
        "Over-entitlement reissue ($4,120 on $412)",
        "A resident messages: 'My payment never came.'",
        "The assistant proposes reissuing $4,120 (ten times the entitlement) for September.",
        scenario_b)),
    ("c", lambda: scenario(
        "Duplicate reissue (already paid by hand)",
        "A resident messages again: 'I still have not got my September payment.'",
        "The assistant proposes reissuing $412 for September, not knowing a caseworker already did.",
        scenario_c)),
    ("d", lambda: scenario(
        "Case closed mid-decision",
        "A resident asks for a reissue of their $412 September payment.",
        "The assistant decides to reissue $412, but a caseworker closes the case before it is sent.",
        scenario_d)),
    ("e", lambda: scenario(
        "Crash after send, then restart",
        "A resident asks for a reissue of their $412 September payment.",
        "The assistant sends the $412 reissue, then the process crashes before the confirmation.",
        scenario_e)),
    ("f", lambda: scenario(
        "Appointment booking and address change",
        "A resident asks to book an appointment and update their mailing address.",
        "The assistant proposes booking the appointment and changing the address on the case.",
        scenario_f)),
]


def build():
    data = {"office": "Riverside County Benefits Office (fictional)",
            "generated_by": "python experiments/civic_story.py",
            "note": ("Case system, ledger and scheduler are simulated; the payment rail is "
                     "Stripe test mode (here simulated, tier 1). Every panel is produced by "
                     "the real Interlock engine."),
            "scenarios": []}
    for key, run in SCENARIOS:
        body = run()
        body["key"] = key
        data["scenarios"].append(body)
    return data


def write(data):
    text = "window.CIVIC = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n"
    out_path = os.path.join(ROOT, "demo", "civic_data.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    return out_path, len(text)


def main():
    data = build()
    out_path, size = write(data)
    # A quick integrity check: every receipt verifies, and none overclaims.
    for s in data["scenarios"]:
        receipts = [s["receipt"]] + [a["receipt"] for a in s.get("sub_actions", [])]
        for r in receipts:
            assert r["verified"], f"scenario {s['key']} receipt did not verify"
            if r["executed"] is not True:
                assert r["executed"] in (False, "unknown"), s["key"]
    print(f"wrote {os.path.relpath(out_path, ROOT)}: {size} bytes, {len(data['scenarios'])} scenarios")
    for s in data["scenarios"]:
        print(f"  {s['key']}: {s['title']} -> {s['gate_outcome']}")


if __name__ == "__main__":
    main()
